CREATE TABLE setores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    sigla VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    descricao VARCHAR(1000) NOT NULL,
    setor_id BIGINT NOT NULL REFERENCES setores(id)
);

CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    matricula VARCHAR(30) NOT NULL,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('SOLICITANTE', 'TECNICO')),
    setor_id BIGINT REFERENCES setores(id),
    CONSTRAINT ck_usuario_setor CHECK (
        (tipo = 'TECNICO' AND setor_id IS NOT NULL)
        OR (tipo = 'SOLICITANTE' AND setor_id IS NULL)
    )
);

CREATE UNIQUE INDEX uk_usuario_email_normalizado ON usuarios (LOWER(email));
CREATE UNIQUE INDEX uk_setor_sigla_normalizada ON setores (UPPER(sigla));

CREATE TABLE chamados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(150) NOT NULL,
    descricao VARCHAR(5000) NOT NULL,
    local VARCHAR(150) NOT NULL,
    prioridade VARCHAR(10) NOT NULL DEFAULT 'MEDIA' CHECK (prioridade IN ('BAIXA', 'MEDIA', 'ALTA')),
    status VARCHAR(20) NOT NULL DEFAULT 'ABERTO' CHECK (status IN ('ABERTO', 'EM_ATENDIMENTO', 'RESOLVIDO', 'CANCELADO')),
    data_abertura TIMESTAMP WITH TIME ZONE NOT NULL,
    data_fechamento TIMESTAMP WITH TIME ZONE,
    solucao VARCHAR(5000),
    solicitante_id BIGINT NOT NULL REFERENCES usuarios(id),
    categoria_id BIGINT NOT NULL REFERENCES categorias(id),
    tecnico_id BIGINT REFERENCES usuarios(id),
    CONSTRAINT ck_chamado_ciclo CHECK (
        (status = 'ABERTO' AND tecnico_id IS NULL AND data_fechamento IS NULL AND solucao IS NULL)
        OR (status = 'EM_ATENDIMENTO' AND tecnico_id IS NOT NULL AND data_fechamento IS NULL AND solucao IS NULL)
        OR (status = 'RESOLVIDO' AND tecnico_id IS NOT NULL AND data_fechamento IS NOT NULL
            AND solucao IS NOT NULL AND LENGTH(TRIM(solucao)) > 0)
        OR (status = 'CANCELADO' AND tecnico_id IS NULL AND data_fechamento IS NOT NULL AND solucao IS NULL)
    )
);

CREATE TABLE interacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    texto VARCHAR(5000) NOT NULL,
    data_hora TIMESTAMP WITH TIME ZONE NOT NULL,
    chamado_id BIGINT NOT NULL REFERENCES chamados(id),
    autor_id BIGINT NOT NULL REFERENCES usuarios(id)
);

CREATE INDEX idx_categoria_setor ON categorias (setor_id);
CREATE INDEX idx_usuario_setor ON usuarios (setor_id);
CREATE INDEX idx_chamado_categoria ON chamados (categoria_id);
CREATE INDEX idx_chamado_solicitante ON chamados (solicitante_id);
CREATE INDEX idx_chamado_tecnico ON chamados (tecnico_id);
CREATE INDEX idx_chamado_status_abertura ON chamados (status, data_abertura);
CREATE INDEX idx_interacao_chamado_data ON interacoes (chamado_id, data_hora, id);
CREATE INDEX idx_interacao_autor ON interacoes (autor_id);
